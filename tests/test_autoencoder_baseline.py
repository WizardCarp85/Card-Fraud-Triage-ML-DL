# Autoencoder Baseline Validation Tests

"""Validate the autoencoder baseline run artifacts and metrics (Issue #32)."""

import json
import unittest
from pathlib import Path

import pandas as pd
from evaluation import evaluate_score_files, load_anomaly_scores, load_evaluation_labels

class AutoencoderBaselineTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        # Locate the most recent autoencoder run directory
        runs = sorted(Path("artifacts/phase2").glob("run_*/"), reverse=True)
        cls.run_dir = None
        for r in runs:
            if (r / "models" / "autoencoder").is_dir():
                cls.run_dir = r
                break
        if cls.run_dir is None:
            raise FileNotFoundError("Autoencoder run directory not found.")

        cls.scores_dir = cls.run_dir / "scores"
        cls.val_scores_path = cls.scores_dir / "scores_val.csv"
        cls.test_scores_path = cls.scores_dir / "scores_test.csv"
        # Labels are in the same directory with _labels suffixed (generated by pipeline)
        cls.val_labels_path = cls.run_dir / "preprocessed" / "validation_labels.csv"
        cls.test_labels_path = cls.run_dir / "preprocessed" / "test_labels.csv"
        # Load provenance for reference metrics
        prov_path = cls.run_dir / "provenance.json"
        with open(prov_path, "r", encoding="utf-8") as f:
            cls.provenance = json.load(f)

    def test_score_and_label_files_exist(self) -> None:
        self.assertTrue(self.val_scores_path.is_file(), "validation scores missing")
        self.assertTrue(self.test_scores_path.is_file(), "test scores missing")
        # Labels files are created by the pipeline in the scores directory as well
        self.assertTrue(self.val_labels_path.is_file(), "validation labels missing")
        self.assertTrue(self.test_labels_path.is_file(), "test labels missing")

    def test_score_file_schema(self) -> None:
        df = pd.read_csv(self.val_scores_path, dtype=str)
        self.assertListEqual(list(df.columns), ["row_id", "split", "model", "anomaly_score"],
                             "Score file schema mismatch")
        self.assertTrue((df["split"] == "validation").all())
        self.assertTrue((df["model"] == "autoencoder").all())

    def test_metrics_match_expected(self) -> None:
        # Load scores and labels using repository utilities
        scores = load_anomaly_scores(
            self.val_scores_path,
            expected_split="validation",
            expected_model="autoencoder",
            score_direction="higher_is_more_suspicious",
        )
        labels = load_evaluation_labels(
            self.val_labels_path,
            expected_split="validation",
        )
        # Evaluate
        res = evaluate_score_files(
            self.val_scores_path,
            self.val_labels_path,
            self.test_scores_path,
            self.test_labels_path,
            model="autoencoder",
            score_direction="higher_is_more_suspicious",
        )
        val_row = res.ranking_metrics.loc[res.ranking_metrics["split"] == "validation"].iloc[0]
        test_row = res.ranking_metrics.loc[res.ranking_metrics["split"] == "test"].iloc[0]
        self.assertAlmostEqual(float(val_row["average_precision_ap"]), 0.1912, places=4)
        self.assertAlmostEqual(float(test_row["average_precision_ap"]), 0.3004, places=4)

if __name__ == "__main__":
    unittest.main()

